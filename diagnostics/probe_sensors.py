import usb.core
import usb.util
import time

dev = usb.core.find(idVendor=0x1b17, idProduct=0x6101)
if not dev:
    print("Device not found")
    exit(1)

def reg_r(req, index, length=1):
    return dev.ctrl_transfer(0xc0, req, 1, index, length)

def reg_w(req, value, index):
    dev.ctrl_transfer(0x40, req, value, index, b"")

def read_sensor_register(address):
    # Check if bus busy
    buf = reg_r(0xa1, 0xb33f, 1)
    if not (buf[0] & 0x02):
        print(f"I2C bus busy wait: 0x{buf[0]:02x}")
        return 0
    reg_w(0xa0, address, 0xb33a)
    reg_w(0xa0, 0x02, 0xb339)
    for _ in range(50):
        buf = reg_r(0xa1, 0xb33b, 1)
        if buf[0] == 0:
            break
        time.sleep(0.04)
    ldata = reg_r(0xa1, 0xb33e, 1)[0]
    mdata = reg_r(0xa1, 0xb33d, 1)[0]
    hdata = reg_r(0xa1, 0xb33c, 1)[0]
    return (hdata << 8) | mdata

